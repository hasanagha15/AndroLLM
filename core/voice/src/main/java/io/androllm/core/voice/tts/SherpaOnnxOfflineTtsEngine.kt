import android.content.Context
import com.k2fsa.sherpa.onnx.GeneratedAudio
import com.k2fsa.sherpa.onnx.OfflineTts
import com.k2fsa.sherpa.onnx.OfflineTtsConfig
import com.k2fsa.sherpa.onnx.OfflineTtsModelConfig
import com.k2fsa.sherpa.onnx.OfflineTtsVitsModelConfig
import dagger.hilt.android.qualifiers.ApplicationContext
import io.androllm.core.voice.VoiceSettingsStore
import io.androllm.core.voice.lang.TtsVoiceKind
import io.androllm.core.voice.lang.VoiceLanguage
import io.androllm.core.voice.lang.VoiceLanguagePolicy
import io.androllm.core.voice.model.VoiceModels
import io.androllm.core.voice.tts.normalize.TextNormalizationEngine
import javax.inject.Inject
import javax.inject.Singleton
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.flow.distinctUntilChanged
import kotlinx.coroutines.flow.map
import kotlinx.coroutines.launch
import timber.log.Timber

/**
 * sherpa-onnx offline TTS backend for [OfflineTtsEngine] (VITS).
 *
 * Synthesizes one sentence at a time on a background thread while the next
 * sentence is still being generated by the model — this is what makes the
 * assistant "start speaking immediately" instead of waiting for the whole
 * answer.
 *
 * Two voices: the bundled English `vits-ljs` (APK assets) and an on-demand
 * Russian Piper voice ([TtsVoiceManager], filesystem). The voice per sentence
 * is chosen by [VoiceLanguagePolicy.ttsVoiceFor] from the voice language
 * setting; each model loads lazily on first use.
 */
@Singleton
class SherpaOnnxOfflineTtsEngine @Inject constructor(
    @ApplicationContext private val context: Context,
    private val textNormalization: TextNormalizationEngine,
    private val settingsStore: VoiceSettingsStore,
    private val voiceManager: TtsVoiceManager
) : OfflineTtsEngine {

    private var tts: OfflineTts? = null
    private var russianTts: OfflineTts? = null
    private var russianVoiceId: String? = null
    /** "<voice id>:<model mtime>" of a voice that failed to load — not retried per sentence. */
    private var russianFailedKey: String? = null

    /** Voice language mirrored from settings (ensureInitialized is not suspend). */
    @Volatile private var language: VoiceLanguage = VoiceLanguage.DEFAULT

    /** Sample rate of the most recent synthesis (both voices are 22050 Hz today). */
    @Volatile private var lastSampleRate: Int = 22050

    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.Default)

    init {
        scope.launch {
            runCatching {
                settingsStore.settings
                    .map { VoiceLanguage.fromCode(it.sttLanguage) }
                    .distinctUntilChanged()
                    .collect { language = it }
            }.onFailure { Timber.w(it, "TTS: voice language observer failed") }
        }
    }

    /**
     * Lowercase word set from the VITS lexicon. Words missing from it are
     * dropped mid-synthesis by sherpa-onnx ("OOV x, ignore it!"), so we
     * re-spell them letter-by-letter instead. Built lazily on first init.
     */
    private var lexicon: Set<String>? = null

    /**
     * Providers tried in order when (re)initializing the model.
     *
     *  - "nnapi"  : Android NN API — offloads supported ops to the GPU/NPU
     *    (fastest for long texts when the device HAL cooperates; VITS graphs
     *    fall back to CPU per-op inside onnxruntime when not supported).
     *  - "xnnpack": onnxruntime XNNPACK EP — multi-threaded SIMD CPU inference,
     *    a solid 2-3x over the default provider on Oryon-class cores.
     *  - "cpu"    : the default, always works.
     *
     * The chain is verified with a probe synthesis so a provider that
     * initializes but only produces silence is rejected instead of shipped.
     */
    private val providerPriority = listOf("nnapi", "xnnpack", "cpu")

    override val isInitialized: Boolean get() = tts != null || russianTts != null

    override val sampleRate: Int get() = lastSampleRate

    private fun russianVoiceInstalled(): Boolean = voiceManager.isInstalled(TtsVoices.DEFAULT_RU)

    /**
     * Makes sure at least the voice for the current language can speak:
     * the Russian voice when the language wants it and it is downloaded,
     * otherwise the bundled English one.
     */
    @Synchronized
    override fun ensureInitialized(): Boolean {
        val lang = language
        if (lang == VoiceLanguage.RU && russianVoiceInstalled()) {
            if (ensureRussian()) return true
            Timber.w("TTS: Russian voice failed to load — falling back to bundled English")
        } else if (lang == VoiceLanguage.RU) {
            Timber.w("TTS: Russian voice not downloaded (Settings → Voice language) — using bundled English")
        }
        return ensureEnglish()
    }

    @Synchronized
    private fun ensureEnglish(): Boolean {
        if (tts != null) return true
        val hasAssets = hasAsset(VoiceModels.TTS_MODEL) && hasAsset(VoiceModels.TTS_TOKENS)
        if (!hasAssets) {
            Timber.w("SherpaOnnxOfflineTtsEngine: TTS assets missing")
            return false
        }
        for (provider in providerPriority) {
            val candidate = createEnglishTts(provider)
            if (candidate != null) {
                tts = candidate
                lexicon = try {
                    val words = context.assets.open(VoiceModels.TTS_LEXICON)
                        .bufferedReader().useLines { lines ->
                            lines.map { it.substringBefore(' ').lowercase() }
                                .filter { it.isNotEmpty() }
                                .toHashSet()
                        }
                    Timber.i("SherpaOnnxOfflineTtsEngine: lexicon loaded (${words.size} words)")
                    words
                } catch (t: Throwable) {
                    Timber.w(t, "TTS lexicon read failed — OOV spelling disabled")
                    null
                }
                Timber.i("SherpaOnnxOfflineTtsEngine: initialized (provider=$provider)")
                return true
            }
        }
        return false
    }

    @Synchronized
    private fun ensureRussian(): Boolean {
        val voice = TtsVoices.DEFAULT_RU
        if (russianTts != null && russianVoiceId == voice.id) return true
        val installed = voiceManager.installed(voice) ?: return false
        val key = "${voice.id}:${installed.model.lastModified()}"
        if (russianFailedKey == key) return false
        for (provider in providerPriority) {
            val candidate = probe(provider, "тест") {
                val vits = OfflineTtsVitsModelConfig().apply {
                    model = installed.model.absolutePath
                    tokens = installed.tokens.absolutePath
                    dataDir = installed.espeakDataDir.absolutePath
                    lexicon = ""
                    noiseScale = 0.667f
                    noiseScaleW = 0.8f
                    lengthScale = 1.0f
                }
                // Filesystem paths: no AssetManager.
                OfflineTts(null, config(vits, provider))
            }
            if (candidate != null) {
                runCatching { russianTts?.release() }
                russianTts = candidate
                russianVoiceId = voice.id
                Timber.i("SherpaOnnxOfflineTtsEngine: Russian voice ${voice.id} initialized (provider=$provider)")
                return true
            }
        }
        russianFailedKey = key
        Timber.w("SherpaOnnxOfflineTtsEngine: Russian voice ${voice.id} failed on all providers — not retrying until reinstalled")
        return false
    }

    private fun config(vits: OfflineTtsVitsModelConfig, provider: String): OfflineTtsConfig {
        val ttsModel = OfflineTtsModelConfig().apply {
            this.vits = vits
            // NNAPI takes over threading itself; the CPU EPs get more threads.
            numThreads = if (provider == "nnapi") 2 else 4
            debug = false
            this.provider = provider
        }
        return OfflineTtsConfig().apply {
            model = ttsModel
            silenceScale = 0.8f
        }
    }

    private fun createEnglishTts(provider: String): OfflineTts? = probe(provider, "test") {
        val vits = OfflineTtsVitsModelConfig().apply {
            model = VoiceModels.TTS_MODEL
            tokens = VoiceModels.TTS_TOKENS
            lexicon = VoiceModels.TTS_LEXICON
            noiseScale = 0.667f
            noiseScaleW = 0.8f
            lengthScale = 1.0f
        }
        OfflineTts(context.assets, config(vits, provider))
    }

    /**
     * Creates an engine with [factory] and probes it: some EPs (NNAPI partial
     * offloads, etc.) create a session but only ever return silence. A silent
     * probe must not stick.
     */
    private fun probe(provider: String, probeText: String, factory: () -> OfflineTts?): OfflineTts? = runCatching {
        val candidate = factory()
        if (candidate == null) {
            Timber.w("SherpaOnnxOfflineTtsEngine: provider $provider failed to init")
            return@runCatching null
        }
        val probe = candidate.generate(probeText, 0, 1.0f)
        val probePeak = probe?.samples?.let(::peakAbs) ?: 0f
        if (probePeak < 0.01f) {
            Timber.w("SherpaOnnxOfflineTtsEngine: provider $provider produced silent probe — rejecting")
            runCatching { candidate.release() }
            return@runCatching null
        }
        candidate
    }.onFailure { Timber.e(it, "TTS init failed (provider=$provider)") }.getOrNull()

    private fun peakAbs(samples: FloatArray): Float {
        var peak = 0f
        for (s in samples) {
            val a = if (s < 0f) -s else s
            if (a > peak) peak = a
        }
        return peak
    }

    /**
     * Synthesizes [text] to a full PCM buffer (mono floats).
     * [speed] is the speaking rate (0.5..2.0). Returns null on failure.
     *
     * The model loads lazily on first use: the assistant spends most of its
     * life listening for the wake word, and pinning the ~114 MB VITS model in
     * RAM 24/7 invites low-memory kills on smaller devices.
     */
    override fun synthesize(text: String, speed: Float): FloatArray? {
        if (text.isBlank()) return null
        val kind = VoiceLanguagePolicy.ttsVoiceFor(language, text, russianVoiceInstalled())
        if (kind == TtsVoiceKind.RUSSIAN && ensureRussian()) {
            val r = russianTts
            if (r != null) return synthesizeRussian(r, text, speed)
        }
        if (!ensureEnglish()) return null
        val t = tts ?: return null
        return runCatching {
            // Spoken text = LLM output through the text-normalization
            // pipeline (numbers, dates, currencies, units, math, emoji,
            // URLs, phones, abbreviations) — never prompt-modified.
            val normalized = textNormalization.normalize(text).text
            if (normalized.isBlank()) return null
            // Anything still outside the VITS lexicon (brands, jargon) would
            // be silently dropped by the model — spell it instead ("LLM"→"l l m").
            val covered = lexicon?.let { EnglishTtsNormalizer.spellOutOfLexicon(normalized, it) } ?: normalized
            Timber.d("TTS: speaking '${covered}'")
            val audio: GeneratedAudio = t.generate(covered, 0, speed.coerceIn(0.5f, 2.0f))
            lastSampleRate = audio.sampleRate.takeIf { it > 0 } ?: t.sampleRate()
            audio.samples
        }.onFailure { Timber.e(it, "TTS synth failed") }.getOrNull()
    }

    /**
     * Russian path: the English normalization pipeline would turn digits into
     * English words, so it is skipped — espeak-ng (inside Piper) reads
     * Russian numbers itself. Only markdown/emoji noise is stripped.
     */
    private fun synthesizeRussian(r: OfflineTts, text: String, speed: Float): FloatArray? = runCatching {
        val cleaned = RussianTtsText.clean(text)
        if (cleaned.isBlank()) return null
        Timber.d("TTS[ru]: speaking '$cleaned'")
        val audio: GeneratedAudio = r.generate(cleaned, 0, speed.coerceIn(0.5f, 2.0f))
        lastSampleRate = audio.sampleRate.takeIf { it > 0 } ?: r.sampleRate()
        audio.samples
    }.onFailure { Timber.e(it, "TTS[ru] synth failed") }.getOrNull()

    @Synchronized
    override fun release() {
        runCatching { tts?.release() }
        runCatching { russianTts?.release() }
        tts = null
        russianTts = null
        russianVoiceId = null
    }

    private fun hasAsset(path: String): Boolean =
        runCatching { context.assets.open(path).close(); true }.getOrDefault(false)
}

/** Text cleanup for the Russian Piper voice (unit-tested). */
object RussianTtsText {
    private val MARKDOWN = Regex("[*_`#~>|]+")
    private val NON_SPEECH = Regex("[\\p{So}\\p{Cs}\\p{Co}]+")
    private val SPACES = Regex("\\s+")

    fun clean(text: String): String =
        text.replace(MARKDOWN, " ")
            .replace(NON_SPEECH, " ")
            .replace(SPACES, " ")
            .trim()
}
